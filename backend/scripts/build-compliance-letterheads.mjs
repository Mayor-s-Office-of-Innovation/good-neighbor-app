// Render the retained DOCX files first (see assets/compliance-letterheads/README.md).
// Embed first-page PDF artwork and its matching PNG so esbuild includes both in
// the worker without filesystem paths or an Office runtime in Lambda.
import { readFile, writeFile } from "node:fs/promises";
import { PDFDocument } from "pdf-lib";
import sharp from "sharp";

const [dphPdf, dphPng, hshPdf, hshPng] = process.argv.slice(2);
if (!dphPdf || !dphPng || !hshPdf || !hshPng) {
  throw new Error(
    "Usage: node scripts/build-compliance-letterheads.mjs DPH.pdf DPH.png HSH.pdf HSH.png",
  );
}
const artwork = {};
for (const [department, pdfPath, pngPath] of [
  ["dph", dphPdf, dphPng],
  ["hsh", hshPdf, hshPng],
]) {
  const source = await PDFDocument.load(await readFile(pdfPath));
  const pdf = await PDFDocument.create();
  const [page] = await pdf.copyPages(source, [0]);
  pdf.addPage(page);
  pdf.setProducer("Good Neighbor app");
  pdf.setCreator("Good Neighbor app");
  pdf.setCreationDate(new Date("2026-10-27T00:00:00Z"));
  pdf.setModificationDate(new Date("2026-10-27T00:00:00Z"));
  artwork[department] = {
    pdf: Buffer.from(await pdf.save()).toString("base64"),
    png: (
      await sharp(await readFile(pngPath))
        .resize(1224, 1584)
        .png()
        .toBuffer()
    ).toString("base64"),
  };
}
await writeFile(
  new URL("../src/domain/compliance-letterhead-artwork.js", import.meta.url),
  `// Generated by scripts/build-compliance-letterheads.mjs; do not edit.\nexport const letterheadArtwork = ${JSON.stringify(artwork, null, 2)};\n`,
);
